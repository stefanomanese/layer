import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Command } from "commander";
import chalk from "chalk";
import { readConfig } from "../utils/config.ts";

const LAYER_VERSION = "0.1.0";

// Old versions injected this block into CLAUDE.md; setup strips it.
const LEGACY_BLOCK = /\n*<!-- layer:start -->[\s\S]*?<!-- layer:end -->\n*/;

const LAYER_SKILL = `---
name: layer
description: How to use Layer (lr), this project's store of agent expertise — load records before editing files, and record conventions, patterns, decisions and failures worth keeping. Use when editing code in a Layer project, when finishing a task, or when running lr commands.
---

<!-- Generated by lr setup claude (v${LAYER_VERSION}). Re-run it to update; local edits are overwritten. -->

# Layer

Expertise records live in \`.layer/\`, grouped by domain. \`lr prime\` runs at session start.

## Before editing

\`\`\`bash
lr prime --files src/foo.ts    # load only the records anchored to that path
lr search "<query>"             # full-text search across active records
\`\`\`

## Before you finish

\`\`\`bash
lr learn                                        # see changed files and their domains
lr record <domain> <type> --description "..."   # capture the insight
lr sync                                         # validate, stage, commit
\`\`\`

Record types: \`convention\` · \`pattern\` · \`failure\` · \`decision\` · \`reference\` · \`guide\`. No domains yet? Add one with \`lr add <domain>\`.

Only record what a future agent would really need. Skip it when nothing new came up, because filler records are noise.

## Upkeep

\`lr status\` shows domain health, and \`lr doctor\` (with \`--fix\`) checks record integrity. \`lr prune\` soft-archives stale records to \`.layer/archive/\`, and \`lr restore <id>\` brings one back.
`;

const SUPPORTED_PROVIDERS = ["claude"];

export function registerSetupCommand(program: Command): void {
	program
		.command("setup <provider>")
		.description("Wire Layer into an AI agent (claude)")
		.action((provider: string) => {
			const cwd = process.cwd();
			readConfig(cwd);

			if (!SUPPORTED_PROVIDERS.includes(provider)) {
				console.error(chalk.red(`✗ Unknown provider "${provider}". Supported: ${SUPPORTED_PROVIDERS.join(", ")}`));
				process.exitCode = 1;
				return;
			}

			if (provider === "claude") {
				setupClaude(cwd);
			}
		});
}

function setupClaude(cwd: string): void {
	let settingsChanged = false;

	// 1. Wire SessionStart hook into .claude/settings.json
	const settingsPath = join(cwd, ".claude", "settings.json");
	const settingsDir = join(cwd, ".claude");

	if (!existsSync(settingsDir)) {
		// Try root settings if no .claude/ folder
		console.log(chalk.yellow("⚠ No .claude/ directory found — creating .claude/settings.json"));
	}

	let settings: Record<string, unknown> = {};
	if (existsSync(settingsPath)) {
		settings = JSON.parse(readFileSync(settingsPath, "utf-8")) as Record<string, unknown>;
	}

	const hook = { type: "command", command: "lr prime 2>/dev/null || true" };
	const hooks = (settings.hooks ?? {}) as Record<string, unknown>;
	const sessionStart = (hooks.SessionStart ?? []) as Array<{ matcher: string; hooks: unknown[] }>;

	const alreadyWired = sessionStart.some((entry) =>
		(entry.hooks ?? []).some(
			(h) => typeof h === "object" && h !== null && (h as { command?: string }).command?.includes("lr prime"),
		),
	);

	if (!alreadyWired) {
		sessionStart.push({ matcher: "", hooks: [hook] });
		hooks.SessionStart = sessionStart;
		settings.hooks = hooks;

		// Ensure directory exists
		if (!existsSync(settingsDir)) {
			mkdirSync(settingsDir, { recursive: true });
		}
		writeFileSync(settingsPath, JSON.stringify(settings, null, "\t") + "\n", "utf-8");
		settingsChanged = true;
	}

	// 2. Skill file — loaded by the agent on demand, not every session
	const skillDir = join(cwd, ".claude", "skills", "layer");
	const skillPath = join(skillDir, "SKILL.md");
	const skillChanged = !existsSync(skillPath) || readFileSync(skillPath, "utf-8") !== LAYER_SKILL;
	if (skillChanged) {
		mkdirSync(skillDir, { recursive: true });
		writeFileSync(skillPath, LAYER_SKILL, "utf-8");
	}

	// 3. Remove the block older versions put in CLAUDE.md
	const claudeMdPath = join(cwd, "CLAUDE.md");
	let legacyRemoved = false;
	if (existsSync(claudeMdPath)) {
		const content = readFileSync(claudeMdPath, "utf-8");
		if (LEGACY_BLOCK.test(content)) {
			const cleaned = content.replace(LEGACY_BLOCK, "\n\n").trim();
			writeFileSync(claudeMdPath, cleaned ? `${cleaned}\n` : "", "utf-8");
			legacyRemoved = true;
		}
	}

	// Report
	if (settingsChanged) {
		console.log(chalk.green("✓ SessionStart hook added to .claude/settings.json"));
	} else {
		console.log(chalk.dim("  SessionStart hook already present in .claude/settings.json"));
	}

	if (skillChanged) {
		console.log(chalk.green("✓ Layer skill written to .claude/skills/layer/SKILL.md"));
	} else {
		console.log(chalk.dim("  Layer skill already up to date"));
	}

	if (legacyRemoved) {
		console.log(chalk.green("✓ Removed old Layer block from CLAUDE.md"));
	}

	console.log(chalk.green("\n✓ Layer is wired into Claude Code"));
	console.log(chalk.dim("  lr prime will run automatically at the start of every session"));
}
